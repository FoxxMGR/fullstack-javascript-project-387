/**
 * Нерабочие праздничные дни Российской Федерации (ст. 112 ТК РФ).
 *
 * Перечень фиксированных дат. Пасха и «перенос» выходных не учитываются —
 * для календаря бронирования достаточно исключить официально нерабочие даты.
 */

const FIXED_HOLIDAYS: Array<{ month: number; day: number }> = [
  { month: 0, day: 1 },  // 1 января — Новый год
  { month: 0, day: 2 },  // 2 января
  { month: 0, day: 3 },  // 3 января
  { month: 0, day: 4 },  // 4 января
  { month: 0, day: 5 },  // 5 января
  { month: 0, day: 6 },  // 6 января — Рождество Христово
  { month: 0, day: 7 },  // 7 января — Рождество Христово
  { month: 0, day: 8 },  // 8 января
  { month: 1, day: 23 }, // 23 февраля — День защитника Отечества
  { month: 2, day: 8 },  // 8 марта — Международный женский день
  { month: 4, day: 1 },  // 1 мая — Праздник Весны и Труда
  { month: 4, day: 9 },  // 9 мая — День Победы
  { month: 5, day: 12 }, // 12 июня — День России
  { month: 10, day: 4 }, // 4 ноября — День народного единства
];

/** Является ли дата нерабочим праздничным днём. */
export function isHoliday(date: Date): boolean {
  const month = date.getMonth();
  const day = date.getDate();
  return FIXED_HOLIDAYS.some((h) => h.month === month && h.day === day);
}
